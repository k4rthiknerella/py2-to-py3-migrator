# -*- coding: utf-8 -*-
"""The data py2scan/py27 takes from Python 2.7.18 itself, written as modules so
py2scan needs no 2.7 at scan time:

  py2scan/py27/symbol.py        the symbol module (grammar symbol numbers)
  py2scan/py27/unicode52.py     the code points unicodedata (Unicode 5.2.0) names
  py2scan/py27/codecs27_data.py the codec registry (encodings.aliases and the
                                encodings modules), the charmaps of the codecs
                                whose 3.x tables differ, and nameprep's table B.3

  python .py-migrate/py27_data.py write    on 2.7: regenerate the modules
  python .py-migrate/py27_data.py check    on 2.7: exit 1 unless they are current,
                                           and grammar.py's token numbers are 2.7's
"""
import io
import os
import pkgutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, "py2scan", "py27")
HEADER = u"# -*- coding: utf-8 -*-\n"


def wrapped(items, indent=4, width=100):
    """items, space-separated, in lines of at most width columns; no item is split."""
    lines = [[]]
    for item in items:
        if lines[-1] and indent + len(u" ".join(lines[-1] + [item])) > width:
            lines.append([])
        lines[-1].append(item)
    return u"\n".join(u" " * indent + u" ".join(line) for line in lines)


def symbol_module():
    import symbol
    lines = [HEADER, u'"""Python 2.7\'s symbol module: the number of each grammar symbol, which\n'
             u'Python 3.10 removed. Generated by .py-migrate/py27_data.py on Python %s."""\n\n'
             % platform_version()]
    for number in sorted(symbol.sym_name):
        lines.append(u"%s = %d\n" % (symbol.sym_name[number], number))
    lines.append(u"\nsym_name = dict((value, name) for name, value in list(globals().items())\n"
                 u"                if isinstance(value, int) and not name.startswith('_'))\n")
    return u"".join(lines)


def named_ranges():
    import unicodedata
    ranges = []
    for code in range(sys.maxunicode + 1):
        if unicodedata.name(unichr(code), None) is None:  # noqa: F821 (2.7 only)
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ranges


def unicode52_module():
    import unicodedata
    ranges = named_ranges()
    items = [u"(0x%X, 0x%X)," % (first, last) for first, last in ranges]
    return u"".join([
        HEADER,
        u'"""The code points that have a name in Unicode %s, the database Python 2.7\'s\n'
        u"unicodedata module and \\\\N{...} escapes use, as inclusive ranges. Generated by\n"
        u'.py-migrate/py27_data.py on Python %s by listing every code point\n'
        u'unicodedata.name() names."""\n\n' % (unicodedata.unidata_version, platform_version()),
        u"NAMED = (\n", wrapped(items), u"\n)\n"])


# The codecs whose charmap 2.7 defines differently from 3.x (measured with
# .py-migrate/codec_parity.py): their non-identity entries.
CHARMAP_CODECS = ("palmos", "rot_13")


def charmap(module):
    mod = __import__("encodings." + module, fromlist=["*"])
    return sorted((byte, value) for byte, value in mod.decoding_map.items() if byte != value)


def b3_pairs():
    """(code point, what stringprep.map_table_b3 maps it to) where that differs
    from the code point: 2.7's b3_exceptions, else unicode.lower() of 5.2."""
    import stringprep
    pairs = []
    for code in range(sys.maxunicode + 1):
        char = unichr(code)  # noqa: F821 (2.7 only)
        mapped = stringprep.map_table_b3(char)
        if mapped != char:
            pairs.append((code, u"".join(u"\\u%04x" % ord(c) if ord(c) < 0x10000 else u"\\U%08x" % ord(c)
                                         for c in mapped)))
    return pairs


def registers(module):
    """Whether encodings.search_function finds a codec in the module on this platform."""
    try:
        return hasattr(__import__("encodings." + module, fromlist=["*"]), "getregentry")
    except ImportError:
        return False


def codecs_module():
    import encodings
    import encodings.aliases
    modules = sorted(name for _, name, _ in pkgutil.iter_modules(encodings.__path__) if registers(name))
    aliases = sorted(encodings.aliases.aliases.items())
    out = [HEADER, u'"""Python 2.7\'s codec registry and the codec data py2scan cannot take from\n'
           u"the running interpreter. Generated by .py-migrate/py27_data.py on Python %s.\n\n"
           u"MODULES are the encodings modules that register a codec; ALIASES is encodings.aliases.aliases;\n"
           u"CHARMAPS has the non-identity entries of the decoding maps of %s;\n"
           u"B3 maps each code point stringprep.map_table_b3 changes (RFC 3454 table B.3,\n"
           u'used by nameprep) to what it becomes: b3_exceptions, else unicode.lower()."""\n\n'
           % (platform_version(), u" and ".join(CHARMAP_CODECS))]
    out.append(u"MODULES = frozenset((\n%s\n))\n\n" % wrapped([u'"%s",' % m for m in modules]))
    out.append(u"ALIASES = {\n%s\n}\n\n" % wrapped([u'"%s": "%s",' % pair for pair in aliases]))
    out.append(u"CHARMAPS = {\n")
    for module in CHARMAP_CODECS:
        entries = wrapped([u"0x%02X: 0x%04X," % p for p in charmap(module)], 8)
        out.append(u'    "%s": {\n%s\n    },\n' % (module, entries))
    out.append(u"}\n\n")
    out.append(u"B3 = {\n%s\n}\n" % wrapped([u'0x%X: u"%s",' % p for p in b3_pairs()]))
    return u"".join(out)


def platform_version():
    return u"%d.%d.%d" % sys.version_info[:3]


MODULES = (("symbol.py", symbol_module), ("unicode52.py", unicode52_module), ("codecs27_data.py", codecs_module))


def token_numbers_differ():
    """The names whose number in py2scan/py27/grammar.py is not 2.7's token module's."""
    import token
    sys.path.insert(0, ROOT)
    from py2scan.py27 import grammar
    numbers = dict((name, value) for name, value in vars(token).items() if isinstance(value, int))
    return sorted(name for name, value in numbers.items() if getattr(grammar, name, None) != value)


def main(argv):
    if sys.version_info[:3] != (2, 7, 18) or argv not in (["write"], ["check"]):
        sys.stderr.write(__doc__)
        return 2
    stale = []
    for name, generate in MODULES:
        path = os.path.join(TARGET, name)
        text = generate()
        if argv == ["write"]:
            with io.open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("wrote %s" % path)
            continue
        with io.open(path, encoding="utf-8") as f:
            if f.read() != text:
                stale.append(name)
    for name in stale:
        print("STALE %s" % name)
    if argv == ["check"]:
        tokens = token_numbers_differ()
        stale.extend(tokens)
        print("%d of %d modules current; token numbers differ: %s" % (
            len(MODULES) - len(stale) + len(tokens), len(MODULES), ", ".join(tokens) or "none"))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
